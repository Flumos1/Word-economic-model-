"""First evaluation pilot report: structure, provenance and the no-admission rule."""
import hashlib
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "protocols" / "first_evaluation_report.json"


class FirstEvaluationPilot(unittest.TestCase):
    def test_report_is_a_pilot_with_provenance(self):
        if not REPORT.exists():
            self.skipTest("the pilot report is generated by tools/run_first_evaluation.py")
        r = json.loads(REPORT.read_text(encoding="utf-8"))
        self.assertEqual(r["report_id"], "AMFE-FIRST-EVALUATION-PILOT")
        self.assertTrue(r["pilot"])
        self.assertFalse(r["admission"], "the pilot must not assign admission")
        self.assertTrue(r["deferred"])
        self.assertEqual(r["protocol"]["version"], "4.0.0")
        self.assertTrue(r["r3_specification"]["version"].startswith("0.6"))
        self.assertIn("sha256", r["composition"])
        pairs = [p for p in r["pairs"] if "relative_loss" in p]
        self.assertGreaterEqual(len(pairs), 15)
        for p in pairs:
            self.assertGreater(p["origins"], 0)
            self.assertGreater(p["threshold"], 0.0)
            self.assertLessEqual(p["threshold"], 0.97)
            self.assertIn(p["loss"], {"RMSE", "Brier", "log_score"})
        self.assertIn("c1_pass_pairs", r["summary"])

    def test_pilot_report_does_not_contain_raw_series(self):
        r = json.loads(REPORT.read_text(encoding="utf-8"))
        text = json.dumps(r, ensure_ascii=False)
        self.assertNotIn("latest.csv", text)
        self.assertNotIn("vintages.zip", text)


if __name__ == "__main__":
    unittest.main(verbosity=2)
