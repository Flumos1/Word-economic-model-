"""Catalog of the stage-5 dynamic mechanisms with the docs/38 epistemic classification.

Every entry is a :class:`amfe.dynamics.base.Mechanism`.  The catalog is validated as a whole:
ids are unique, all five kinds are represented, hypotheses name the tests that could refute them,
scenarios neither gate admission nor claim causality.  ``docs/80`` is generated by hand from
``catalog_table()`` and must stay consistent with it.
"""
from __future__ import annotations

from .base import (MECHANISM_KINDS, Mechanism, catalog_table, mechanism_counts,
                   validate_catalog)
from .debt import DEBT_DYNAMICS_MECHANISM, DEBT_STRESS_MECHANISM
from .diffusion import (ADOPTION_CEILING_MECHANISM, BASS_DIFFUSION_MECHANISM,
                        LOGISTIC_DIFFUSION_MECHANISM)
from .expectations import (ADAPTIVE_EXPECTATIONS_MECHANISM, LEARNING_MECHANISM,
                           RATIONAL_EXPECTATIONS_MECHANISM)
from .geopolitics import GEOPOLITICAL_RISK_MECHANISM
from .policy import INFLATION_TARGET_MECHANISM, TAYLOR_RULE_MECHANISM
from .regimes import MARKOV_SWITCHING_MECHANISM

MECHANISM_CATALOG = (
    MARKOV_SWITCHING_MECHANISM,
    ADAPTIVE_EXPECTATIONS_MECHANISM,
    RATIONAL_EXPECTATIONS_MECHANISM,
    LEARNING_MECHANISM,
    TAYLOR_RULE_MECHANISM,
    INFLATION_TARGET_MECHANISM,
    DEBT_DYNAMICS_MECHANISM,
    DEBT_STRESS_MECHANISM,
    GEOPOLITICAL_RISK_MECHANISM,
    LOGISTIC_DIFFUSION_MECHANISM,
    ADOPTION_CEILING_MECHANISM,
    BASS_DIFFUSION_MECHANISM,
)

MECHANISMS_BY_ID = {mechanism.mechanism_id: mechanism
                    for mechanism in validate_catalog(MECHANISM_CATALOG)}


def mechanism_by_id(mechanism_id: str) -> Mechanism:
    if mechanism_id not in MECHANISMS_BY_ID:
        raise KeyError(f"unknown dynamic mechanism {mechanism_id!r}")
    return MECHANISMS_BY_ID[mechanism_id]


def catalog() -> list:
    return catalog_table(MECHANISM_CATALOG)


def counts() -> dict:
    return mechanism_counts(MECHANISM_CATALOG)


def kinds() -> tuple:
    return MECHANISM_KINDS
