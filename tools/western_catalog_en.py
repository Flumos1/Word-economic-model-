def convert(html_text: str, pdf_path: Path) -> int:
    if not SOFFICE.is_file():
        raise BriefError(f"LibreOffice not found: {SOFFICE}")
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp) / "catalog_en.html"
        source.write_text(html_text, encoding="utf-8", newline="\n")
        if pdf_path.exists():
            pdf_path.unlink()
        completed = subprocess.run(
            [str(SOFFICE), "--headless", "--nolockcheck", "--norestore",
             "--convert-to", "pdf", "--outdir", str(pdf_path.parent), str(source)],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=180,
            env={**__import__("os").environ})
        produced = pdf_path.parent / "catalog_en.pdf"
        if not produced.is_file() or produced.stat().st_size == 0:
            raise BriefError(f"PDF conversion failed: {completed.stdout} {completed.stderr}")
        if produced != pdf_path:
            produced.replace(pdf_path)
    return page_count(pdf_path)


def page_count(path: Path) -> int:
    try:
        from pypdf import PdfReader
    except ImportError as error:  # pragma: no cover - pypdf ships with the test environment
        raise BriefError(f"pypdf is required to count pages: {error}") from error
    return len(PdfReader(str(path)).pages)


def check(pdf_path: Path) -> dict:
    if not pdf_path.is_file():
        raise BriefError(f"missing {pdf_path.relative_to(ROOT)}")
    data = pdf_path.read_bytes()
    if not data.startswith(b"%PDF-"):
        raise BriefError("not a PDF")
    if len(data) < 8000:
        raise BriefError("PDF is suspiciously small")
    pages = page_count(pdf_path)
    if not 2 <= pages <= 4:
        raise BriefError(f"expected 2-4 pages, got {pages}")
    return {"ok": True, "pdf": str(pdf_path.relative_to(ROOT)), "bytes": len(data),
            "pages": pages}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="English brief of the western case catalog")
    parser.add_argument("--out", default=None, help="output PDF (default: site/business/assets/cases/catalog_en.pdf)")
    parser.add_argument("--check", action="store_true", help="validate the committed PDF only")
    parser.add_argument("--generated-at", default=None, help="ISO date stamped into the brief")
    args = parser.parse_args(argv)
    pdf_path = Path(args.out) if args.out else OUT_PDF
    try:
        if args.check:
            print(json.dumps(check(pdf_path), ensure_ascii=False))
            return 0
        _catalog, cases, manifest = load()
        generated_at = args.generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%d")
        brief = build_brief(cases, generated_at, manifest)
        pages = convert(render_html(brief), pdf_path)
        summary = check(pdf_path)
        summary.update({"cases": brief["cases"], "companies": brief["companies"],
                        "segments": len(brief["segments"]), "pages": pages})
        print(json.dumps(summary, ensure_ascii=False))
        return 0
    except BriefError as error:
        print(json.dumps({"ok": False, "error": str(error)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
