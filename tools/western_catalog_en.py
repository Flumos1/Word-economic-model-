"""English brief of the western case catalog: ``site/business/assets/cases/catalog_en.pdf``.

The full catalog (50 case cards, Russian) is generated by :mod:`tools.case_catalog`. This tool does
not duplicate it in English: it renders a 2-3 page *brief* — what the catalog is, the coverage by
segment and module, the declared USD price bands, the statuses (``HYPOTHESIS`` / ``NOT_FETCHED``)
and the rules of the package. Every number is read from ``marketing/western_cases/cases.json`` and
``manifest.json``; nothing is typed by hand, so the brief cannot drift from the catalog.

The brief never names a company: a case is a hypothesis about a role, not a client reference.

Usage::

    python tools/western_catalog_en.py            # build the PDF and print a JSON summary
    python tools/western_catalog_en.py --check    # verify the committed PDF without rebuilding
    python tools/western_catalog_en.py --out build/catalog_en_demo

The PDF is not byte-deterministic (LibreOffice metadata); the content is.
"""
from __future__ import annotations

import argparse
import html as html_lib
import json
import subprocess
import sys
import tempfile
from collections import Counter, OrderedDict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / "marketing" / "western_cases" / "cases.json"
MANIFEST = ROOT / "marketing" / "western_cases" / "manifest.json"
OUT_PDF = ROOT / "site" / "business" / "assets" / "cases" / "catalog_en.pdf"
SOFFICE = Path(r"C:\Program Files\LibreOffice\program\soffice.exe")

SEGMENT_LABELS = OrderedDict((
    ("major", "Majors"),
    ("upstream", "Upstream"),
    ("lng", "LNG"),
    ("services", "Oilfield services"),
    ("trading", "Trading"),
    ("chemicals", "Chemicals"),
    ("utilities", "Utilities"),
    ("pipelines", "Pipelines"),
    ("industrials", "Industrials"),
))
PROGRAM_TARGET = 100
# The catalog stores module and band labels in Russian (it is the Russian artifact). The English
# brief translates them by exact key and fails closed on an unknown label instead of printing it.
MODULE_LABELS = OrderedDict((
    ("Ормуз/бюджет", "Hormuz / budget"),
    ("FLAKS TCO", "FLAKS TCO"),
    ("газ/СПГ", "Gas / LNG"),
    ("геополитика", "Geopolitics"),
    ("API/Client Pack", "API / Client Pack"),
))
BAND_LABELS = OrderedDict((
    ("0 — диагностика", "USD 0 - diagnostic"),
    ("7 500-10 000 — пилот", "USD 7,500 - 10,000 - pilot"),
    ("15 000-25 000 — полный сценарий, узкий", "USD 15,000 - 25,000 - full scenario, narrow"),
    ("20 000-30 000 — полный сценарий", "USD 20,000 - 30,000 - full scenario"),
    ("25 000-80 000 — API и подписка", "USD 25,000 - 80,000 - API and subscription"),
))
STATUS_LABELS = OrderedDict((
    ("HYPOTHESIS", "HYPOTHESIS — the pain and the question are constructed for the role, "
                   "not confirmed with the company"),
    ("NOT_FETCHED", "NOT_FETCHED — no public source was fetched for this card, so it carries "
                    "zero factual claims"),
))

CHECKS = ("not client", "not a proposal", "not an offer", "no admission")


class BriefError(RuntimeError):
    pass


def load() -> tuple[dict, list[dict], dict]:
    if not CASES.is_file():
        raise BriefError(f"missing {CASES.relative_to(ROOT)}")
    catalog = json.loads(CASES.read_text(encoding="utf-8"))
    cases = catalog.get("cases") or []
    if not cases:
        raise BriefError("cases.json holds no cases")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else {}
    return catalog, cases, manifest


def module_label(name: str) -> str:
    try:
        return MODULE_LABELS[name]
    except KeyError as error:
        raise BriefError(f"untranslated module label: {name!r}") from error


def segment_table(cases: list[dict]) -> list[dict]:
    rows = []
    for key, label in SEGMENT_LABELS.items():
        group = [case for case in cases if case.get("segment") == key]
        if not group:
            continue
        prices = [int(case["price_usd"]) for case in group]
        weeks = [int(case["duration_weeks"]) for case in group]
        modules = Counter(module_label(module) for case in group for module in case.get("modules", ()))
        rows.append({
            "key": key,
            "label": label,
            "cases": len(group),
            "companies": len({case["company"] for case in group}),
            "price_min": min(prices),
            "price_max": max(prices),
            "weeks_min": min(weeks),
            "weeks_max": max(weeks),
            "module": modules.most_common(1)[0][0] if modules else "—",
            "free": sum(1 for price in prices if price == 0),
        })
    return rows


def money(value: int) -> str:
    return f"{value:,}".replace(",", ",")


def build_brief(cases: list[dict], generated_at: str, manifest: dict | None = None) -> dict:
    segments = segment_table(cases)
    total_cases = len(cases)
    total_companies = len({case["company"] for case in cases})
    modules = Counter(module_label(module) for case in cases for module in case.get("modules", ()))
    statuses = Counter(case.get("evidence_status", "") for case in cases)
    prices = [int(case["price_usd"]) for case in cases]
    weeks = [int(case["duration_weeks"]) for case in cases]
    declared = ((manifest or {}).get("coverage") or {}).get("price_bands") or {}
    bands = []
    for label, count in declared.items():
        try:
            bands.append((BAND_LABELS[label], int(count)))
        except KeyError as error:
            raise BriefError(f"untranslated price band: {label!r}") from error
    if sum(count for _label, count in bands) != total_cases:
        raise BriefError("manifest price bands do not add up to the number of cases")
    return {
        "generated_at": generated_at,
        "cases": total_cases,
        "companies": total_companies,
        "segments": segments,
        "modules": modules.most_common(),
        "statuses": statuses,
        "price_min": min(prices),
        "price_max": max(prices),
        "free": sum(1 for price in prices if price == 0),
        "weeks_min": min(weeks),
        "weeks_max": max(weeks),
        "bands": bands,
    }


def esc(value: object) -> str:
    return html_lib.escape(str(value), quote=False)


def rows_html(rows: list[dict]) -> str:
    out = []
    for row in rows:
        band = ("free diagnostic" if row["price_min"] == row["price_max"] == 0 else
                f"USD {money(row['price_min'])} – {money(row['price_max'])}")
        out.append(
            "<tr>"
            f"<td><b>{esc(row['label'])}</b> <span class=\"dim\">({esc(row['key'])})</span></td>"
            f"<td class=\"num\">{row['cases']}</td>"
            f"<td class=\"num\">{row['companies']}</td>"
            f"<td class=\"num\">{esc(band)}</td>"
            f"<td class=\"num\">{row['weeks_min']}–{row['weeks_max']} w</td>"
            f"<td>{esc(row['module'])}</td>"
            "</tr>")
    return "\n".join(out)


